import fs from 'node:fs/promises';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';
const dir='D:/Sudarshan/app/outputs/rop-export';
const data=JSON.parse(await fs.readFile(`${dir}/data.json`,'utf8'));
if(data.count!==50||new Set(data.rows.map(r=>r.mrd)).size!==50) throw Error('Patient count mismatch');
const wb=Workbook.create();
const s=wb.worksheets.add('Urgent follow-ups');
s.showGridLines=false;
s.getRange('A2').values=[['Urgent: treatment course or ROP']];
s.getRange('A2').format.font={bold:true,size:15};
s.getRange('A3').values=[[`50 patients. Follow-up calls due within the last 90 days. As of ${data.date}.`]];
const headers=['Patient name','MRD No','Contact number','Last visit date','Follow-up date','Last remark'];
s.getRange('A5:F5').values=[headers];
const date=v=>v?new Date(`${v}T00:00:00Z`):null;
const rows=data.rows.map(r=>[r.name,String(r.mrd),String(r.mobile),date(r.lastVisit),date(r.followup),r.remark]);
s.getRange('A6:F55').values=rows;
s.getRange('B6:C55').setNumberFormat('@');
s.getRange('D6:E55').setNumberFormat('dd-mmm-yyyy');
s.tables.add('A5:F55',true,'UrgentFollowups');
s.getRange('A5:F55').format.font={name:'Arial',size:11};
s.getRange('A5:F5').format.fill='#24465A';
s.getRange('A5:F5').format.font={bold:true,color:'#FFFFFF'};
s.getRange('A5:F55').format.verticalAlignment='center';
s.getRange('A5:F5').format.rowHeight=30;
for(const [c,w] of [['A',32],['B',15],['C',20],['D',19],['E',19],['F',85]]) s.getRange(`${c}5:${c}55`).format.columnWidth=w;
s.getRange('A6:F55').format.wrapText=true;
for(let i=0;i<rows.length;i++) s.getRange(`A${i+6}:F${i+6}`).format.rowHeight=Math.max(32,Math.ceil(String(rows[i][5]??'').length/75)*16+12,Math.ceil(String(rows[i][0]).length/28)*16+12);
s.freezePanes.freezeRows(5);
wb.recalculate();
const values=s.getRange('A6:F55').values;
if(values.length!==50||values.some((r,i)=>r[1]!==rows[i][1]||r[2]!==rows[i][2]||r[5]!==rows[i][5])) throw Error('Export validation failed');
await wb.inspect({kind:'table',range:'Urgent follow-ups!A5:F8',maxChars:2000});
await fs.writeFile(`${dir}/preview.png`,new Uint8Array(await (await wb.render({sheetName:s.name,range:'A2:F10',scale:1.3,format:'png'})).arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(wb)).save(`${dir}/Urgent_Followups_50_Patients.xlsx`);
console.log('Validated and exported all 50 patient records.');
